//! The HD44780's character generator ROM, code A00 — the one on nearly every
//! 1602 module: ASCII, with a yen sign for the backslash and two arrows at the
//! top, then a half of katakana and symbols.
//!
//! Each glyph is eight rows of five dots, the top row first and the leftmost
//! dot as bit 4, transcribed from the character table of the datasheet. The
//! eighth row is the cursor's and every ROM glyph leaves it dark.
//!
//! Of the upper half only the two characters sketches reach for are drawn —
//! 0xDF, the small circle printed as a degree sign, and 0xFF, the solid block
//! of bar graphs; the rest show as a hollow box, which no real code is, so a
//! katakana string reads as "not drawn" rather than as wrong text. Codes the
//! ROM leaves empty (0x10–0x1F, 0x80–0x9F) are blank, as on the glass.

