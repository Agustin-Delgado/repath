/// The dots of character code `code` (0x10 and up; below that is CGRAM).
pub fn glyph(code: u8) -> [u8; 8] {
    match code {
        0x20..=0x7F => {
            let rows = LOWER[usize::from(code - 0x20)];
            let mut out = [0; 8];
            out[..7].copy_from_slice(&rows);
            out
        }
        0xDF => [0x1C, 0x14, 0x1C, 0x00, 0x00, 0x00, 0x00, 0x00],
        0xFF => [0x1F; 8],
        0xA1..=0xFE => UNDRAWN,
        // The ROM's empty columns, and 0xA0, its space.
        _ => [0; 8],
    }
}
